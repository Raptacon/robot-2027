class TestWheelRadius:
    @pytest.mark.parametrize("real_radius_m", [0.0508, 0.0490])
    def test_finds_the_real_wheel_radius(self, scheduler, sim_drive, real_radius_m):
        corners = {c.name: CornerSim(actual_wheel_radius_m=real_radius_m) for c in CONFIG.corners}
        sim = make_sim(scheduler, sim_drive, corners=corners)
        command = WheelRadiusCharacterization(sim.drivetrain)
        run_sim_until_done(sim, scheduler, command)
        assert command.radius_m == pytest.approx(real_radius_m, rel=0.005)

    def test_stopped_early_gives_no_answer(self, scheduler, sim_drive):
        sim = make_sim(scheduler, sim_drive)
        command = WheelRadiusCharacterization(sim.drivetrain)
        command.schedule()
        sim.run(1.0)
        command.cancel()
        assert command.radius_m is None


class TestSteerStep:
    def test_reports_settle_time_and_overshoot_for_every_corner(self, scheduler, sim_drive):
        sim = make_sim(scheduler, sim_drive)
        command = SteerStepTest(sim.drivetrain)
        run_sim_until_done(sim, scheduler, command)
        assert set(command.settle_time_s) == {c.name for c in CONFIG.corners}
        for name in command.settle_time_s:
            assert 0.0 < command.settle_time_s[name] < SteerStepTest.STEP_S
            assert 0.0 <= command.overshoot_deg[name] < 20.0

    def test_a_slow_steer_loop_settles_later(self, scheduler, sim_drive):
        settle = []
        for steer_kp in (CONFIG.spark.steer_kp, CONFIG.spark.steer_kp / 3):
            config = dataclasses.replace(CONFIG, spark=SparkSettings(steer_kp=steer_kp))
            sim = make_sim(scheduler, sim_drive, config)
            command = SteerStepTest(sim.drivetrain)
            run_sim_until_done(sim, scheduler, command)
            settle.append(command.settle_time_s["frontLeft"])
            sim.close()  # free the CAN IDs for the next robot
        fast, slow = settle
        assert slow > fast


class TestCalibrateOffsets:
    def test_new_offsets_make_forward_read_zero(self, scheduler, sim_drive):
        errors = {"frontLeft": 0.02, "frontRight": -0.1, "backLeft": 0.3, "backRight": 0.0}
        corners = {name: CornerSim(encoder_offset_error_rot=e) for name, e in errors.items()}
        sim = make_sim(scheduler, sim_drive, corners=corners)
        # The sim wheels start pointing straight forward, as if lined up by hand.
        command = CalibrateOffsets(sim.drivetrain)
        command.initialize()
        assert command.offsets_rot is not None
        for corner, offset in zip(CONFIG.corners, command.offsets_rot):
            # The CANcoder reads in steps of 1/4096 turn.
            assert offset == pytest.approx(wrap_rotations(corner.encoder_offset_rot - errors[corner.name]), abs=1e-3)
            assert -0.5 <= offset < 0.5

    def test_works_while_disabled(self, sim_drive):
        assert CalibrateOffsets(sim_drive().drivetrain).runsWhenDisabled()

    def test_refuses_when_an_encoder_is_missing(self, scheduler, sim_drive):
        sim = make_sim(scheduler, sim_drive)
        # The CANcoder simulator can't stop answering, so mark this loop's
        # reading as missing, the way a dead encoder would read.
        sim.drivetrain.modules[2].encoder_inputs.connected = False
        command = CalibrateOffsets(sim.drivetrain)
        command.initialize()
        assert command.offsets_rot is None

    def test_offsets_wrap(self):
        assert offsets_from_raw([0.75, -0.75, 0.5, 0.0]) == (0.25, -0.25, -0.5, 0.0)


