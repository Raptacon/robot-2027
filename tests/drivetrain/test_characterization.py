def make_sim(scheduler, sim_drive, config=CONFIG, **options):
    """The real drivetrain on the simulated robot, run by the scheduler, after a few loops to settle."""
    sim = sim_drive(config, **options)
    # The current scheduler, not the fixture's: closing a SimDrive starts a new one.
    sim.robot_loop = lambda: commands2.CommandScheduler.getInstance().run()
    for _ in range(10):
        sim.loop()
    return sim


def drive_kv_ka(sim):
    """The simulated drive motor's kV and kA, per meter (SysId's units)."""
    module = sim.physics.modules[0]
    return module.drive.kv / module.drive_m_per_rot, module.drive.ka / module.drive_m_per_rot


def run_sim_until_done(sim, scheduler, command, max_s=60.0):
    """Schedule ``command`` and run simulated loops until it finishes. Returns the seconds it took."""
    command.schedule()
    count = 0
    while commands2.CommandScheduler.getInstance().isScheduled(command) and count < max_s / 0.02:
        sim.loop()
        count += 1
    return count * 0.02


class TestDriveSysId:
    def test_measures_the_simulated_drive_motors(self, scheduler, sim_drive):
        sim = make_sim(scheduler, sim_drive)
        tests = register_swerve(CharacterizationChooser("none", commands2.InstantCommand()), sim.drivetrain)
        run_sim_until_done(sim, scheduler, tests["drive"].all_tests())
        expected_kv, expected_ka = drive_kv_ka(sim)
        fit = tests["drive"].estimate
        assert fit is not None
        assert fit.kv == pytest.approx(expected_kv, rel=0.03)
        assert fit.ka == pytest.approx(expected_ka, rel=0.1)
        assert abs(fit.ks) < 0.05  # the sim has no friction

    def test_wheels_point_straight_and_robot_drives_forward(self, scheduler, sim_drive):
        sim = make_sim(scheduler, sim_drive)
        tests = register_swerve(CharacterizationChooser("none", commands2.InstantCommand()), sim.drivetrain)
        run_sim_until_done(sim, scheduler, tests["drive"].quasistatic(forward=True))
        assert sim.true_pose.x_m > 1.0
        assert abs(sim.true_pose.y_m) < 0.01
        assert abs(sim.true_pose.heading_rad) < math.radians(0.5)
        for angle in sim.true_angles():
            assert abs(angle) < math.radians(1)

    def test_forward_then_reverse_comes_back(self, scheduler, sim_drive):
        sim = make_sim(scheduler, sim_drive)
        tests = register_swerve(CharacterizationChooser("none", commands2.InstantCommand()), sim.drivetrain)
        run_sim_until_done(sim, scheduler, tests["drive"].all_tests())
        assert abs(sim.true_pose.x_m) < 0.5


class TestSlowRampDrive:
    def test_measures_kv_without_ka(self, scheduler, sim_drive):
        sim = make_sim(scheduler, sim_drive)
        chooser = CharacterizationChooser("none", commands2.InstantCommand())
        tests = register_swerve(chooser, sim.drivetrain)
        assert "Drive feedforward (slow)" in chooser.names
        run_sim_until_done(sim, scheduler, tests["driveSlowRamp"].quasistatic(forward=True))
        fit = tests["driveSlowRamp"].estimate
        assert fit is not None
        assert fit.kv == pytest.approx(drive_kv_ka(sim)[0], rel=0.03)
        assert fit.ka == 0.0
        assert 1.0 < sim.true_pose.x_m < 6.0  # creeps a few meters, fits in a hallway


class TestSteerSysId:
    def test_measures_the_simulated_steer_motors(self, scheduler, sim_drive):
        sim = make_sim(scheduler, sim_drive)
        tests = register_swerve(CharacterizationChooser("none", commands2.InstantCommand()), sim.drivetrain)
        run_sim_until_done(sim, scheduler, tests["steer"].all_tests())
        steer = sim.physics.modules[0]
        fit = tests["steer"].estimate
        assert fit is not None
        # kA is too small to measure well at 50 Hz (the steer motor reaches
        # full speed within a loop), so only kV is checked.
        assert fit.kv == pytest.approx(steer.steer.kv / steer.steer_rad_per_rot, rel=0.03)

    def test_drive_motors_stay_off(self, scheduler, sim_drive):
        sim = make_sim(scheduler, sim_drive)
        tests = register_swerve(CharacterizationChooser("none", commands2.InstantCommand()), sim.drivetrain)
        run_sim_until_done(sim, scheduler, tests["steer"].dynamic(forward=True))
        assert math.hypot(sim.true_pose.x_m, sim.true_pose.y_m) < 0.01


