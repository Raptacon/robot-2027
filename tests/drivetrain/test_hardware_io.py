def read_when_ready(encoder, expected_raw, tries=100):
    """Phoenix's simulator delivers new values a few milliseconds later, so wait for this one."""
    inputs = AbsoluteEncoderInputs()
    for _ in range(tries):
        encoder.update_inputs(inputs)
        if inputs.connected and abs(inputs.raw_rot - expected_raw) < 2e-3:
            return inputs
        time.sleep(0.01)
    return inputs


class TestCANcoder:
    def test_accepts_its_settings(self, cancoder):
        assert cancoder.configured

    @pytest.mark.parametrize("raw", [0.1, -0.3, 0.45])
    def test_offset_is_added_and_wrapped(self, cancoder, raw):
        cancoder.encoder.sim_state.set_raw_position(raw)
        inputs = read_when_ready(cancoder, raw)
        assert inputs.connected
        assert inputs.raw_rot == pytest.approx(raw, abs=2e-3)
        expected = math.remainder((raw + TEST_CORNER.encoder_offset_rot) * math.tau, math.tau)
        assert math.remainder(inputs.angle_rad - expected, math.tau) == pytest.approx(0.0, abs=0.01)
        assert -math.pi <= inputs.angle_rad < math.pi


