@pytest.fixture(scope="module")
def spark_module():
    """One SPARK MAX module and its REV simulators, shared by the tests below."""
    io = ModuleIOSpark(CONFIG, TEST_CORNER)
    return io, rev.SparkMaxSim(io.drive, DCMotor.NEO(1)), rev.SparkMaxSim(io.steer, DCMotor.NEO(1))


class TestSparkModule:
    def test_both_controllers_accept_their_settings(self, spark_module):
        io, _, _ = spark_module
        assert io.configured

    def test_drive_counts_in_meters(self, spark_module):
        io, drive_sim, _ = spark_module
        before = ModuleInputs()
        io.update_inputs(before)
        for _ in range(50):  # 1 m/s for 1 s
            drive_sim.iterate(1.0, 12.0, 0.02)
        after = ModuleInputs()
        io.update_inputs(after)
        assert after.drive_position_m - before.drive_position_m == pytest.approx(1.0, rel=1e-3)
        assert after.drive_connected

    def test_steer_angle_is_set_and_wrapped(self, spark_module):
        io, _, _ = spark_module
        inputs = ModuleInputs()
        io.reset_steer_angle(1.0)
        io.update_inputs(inputs)
        assert inputs.steer_angle_rad == pytest.approx(1.0, abs=1e-6)
        io.reset_steer_angle(4.0)  # past pi: reads as 4 - 2 pi
        io.update_inputs(inputs)
        assert inputs.steer_angle_rad == pytest.approx(4.0 - math.tau, abs=1e-6)

    def test_setpoints_are_in_our_units(self, spark_module):
        io, drive_sim, steer_sim = spark_module
        io.set_drive_velocity(2.5, feedforward_volts=3.0)
        io.set_steer_angle(-0.7)
        assert drive_sim.getSetpoint() == pytest.approx(2.5)
        assert steer_sim.getSetpoint() == pytest.approx(-0.7)


class TestSparkSettings:
    """Check the settings themselves, before they are sent to a controller."""

    def flat(self, cfg):
        return cfg.flatten()

    def test_drive_and_steer_settings_differ(self):
        drive = drive_config(CONFIG, CONFIG.corners[0])
        steer = steer_config(CONFIG)
        assert self.flat(drive) != self.flat(steer)

    def test_drive_inversion_follows_the_corner(self):
        normal = dataclasses.replace(CONFIG.corners[0], drive_inverted=False)
        flipped = dataclasses.replace(CONFIG.corners[0], drive_inverted=True)
        assert self.flat(drive_config(CONFIG, normal)) != self.flat(drive_config(CONFIG, flipped))


