from utils.wpimath_compat import Pose2d, Rotation2d


def angle_error(a, b):
    return abs(math.remainder(a - b, math.tau))


def points_along(angle, target, tolerance=math.radians(1)):
    """True if a wheel points at ``target`` or straight the other way (optimize may flip it)."""
    return angle_error(angle, target) < tolerance or angle_error(angle, target + math.pi) < tolerance


class TestDriftWhileRotating:
    """Field-relative straight line while spinning."""

    SPEEDS = ChassisSpeeds(vx_mps=1.5, vy_mps=0.0, omega_rad_per_s=2.0)

    def test_odometry_matches_truth(self, sim_drive):
        sim = sim_drive()
        sim.run(3.0, self.SPEEDS)
        truth = sim.true_pose
        assert truth.x_m > 4.0  # it really drove about 4.2 m
        pose = sim.drivetrain.pose
        assert math.hypot(pose.X() - truth.x_m, pose.Y() - truth.y_m) < 0.01
        assert angle_error(pose.rotation().radians(), truth.heading_rad) < math.radians(0.5)

    @pytest.mark.xfail(
        strict=True,
        reason="With the config's steer kP (0.5) the wheels lag about 6 degrees while spinning, "
        "so the robot drifts about 0.5 m off the line. Tune steer on the robot (M6), then remove this mark.",
    )
    def test_stays_on_line(self, sim_drive):
        sim = sim_drive()
        sim.run(3.0, self.SPEEDS)
        assert abs(sim.true_pose.y_m) < 0.10  # within 10 cm of the line

    def test_discretize_reduces_drift(self, sim_drive, monkeypatch):
        with_disc = sim_drive()
        with_disc.run(3.0, self.SPEEDS)
        drift_with = abs(with_disc.true_pose.y_m)
        with_disc.close()
        monkeypatch.setattr(drivetrain_module, "discretize", lambda s, dt: s)
        without = sim_drive()
        without.run(3.0, self.SPEEDS)
        assert drift_with < abs(without.true_pose.y_m)

    def test_straight_line_without_rotation(self, sim_drive):
        sim = sim_drive()
        sim.run(2.0, ChassisSpeeds(2.0, 0.0, 0.0))
        assert sim.true_pose.x_m > 3.0
        assert abs(sim.true_pose.y_m) < 0.01
        assert abs(sim.true_pose.heading_rad) < math.radians(0.5)

    def test_wrong_gears_make_odometry_drift(self, sim_drive):
        # Config says L2, the modules really have L3: odometry under-reads.
        sim = sim_drive(corners={c.name: CornerSim(actual_preset=MK4I_L3) for c in CONFIG.corners})
        sim.run(2.0, ChassisSpeeds(1.0, 0.0, 0.0))
        assert sim.true_pose.x_m / sim.drivetrain.pose.X() == pytest.approx(6.75 / 6.12, rel=0.02)


class TestSeedingAndHealth:
    def test_wheels_seeded_from_absolute_encoders(self, sim_drive):
        angles = [0.3, -1.0, 2.5, -2.9]
        sim = sim_drive(corners={c.name: CornerSim(initial_angle_rad=a) for c, a in zip(CONFIG.corners, angles)})
        for module, angle in zip(sim.drivetrain.modules, angles):
            assert module.seeded
            assert module.angle_rad == pytest.approx(angle, abs=0.002)
        # Driving forward points every real wheel forward (or backward, after optimize).
        sim.run(0.5, ChassisSpeeds(1.0, 0.0, 0.0), field_relative=False)
        for angle in sim.true_angles():
            assert points_along(angle, 0.0)

    def test_encoder_offset_error_shows_up_as_a_wheel_angle_error(self, sim_drive):
        # The CANcoder offset is 0.01 turns (3.6 degrees) off on one corner.
        sim = sim_drive(corners={"frontRight": CornerSim(encoder_offset_error_rot=0.01)})
        sim.run(0.5, ChassisSpeeds(1.0, 0.0, 0.0), field_relative=False)
        front_right = sim.true_angles()[1]
        assert angle_error(front_right, -0.01 * math.tau) < math.radians(0.5)

    def test_reseed_while_disabled_after_slip(self, sim_drive):
        sim = sim_drive(enabled=False)
        sim.run(0.1)
        module = sim.drivetrain.modules[0]
        module.io.reset_steer_angle(module.angle_rad + math.radians(10))  # steer encoder jumps 10 degrees
        sim.run(0.06)
        assert module.reseed_count == 1
        assert angle_error(module.angle_rad, sim.true_angles()[0]) < math.radians(0.5)

    def test_stopped_wheel_keeps_its_angle(self, sim_drive):
        sim = sim_drive()
        sim.run(0.5, ChassisSpeeds(0.0, 1.0, 0.0), field_relative=False)  # wheels point left
        sim.run(0.5, ChassisSpeeds(), field_relative=False)
        for angle in sim.true_angles():
            assert points_along(angle, math.pi / 2)

    def test_disabled_robot_doesnt_move(self, sim_drive):
        sim = sim_drive(enabled=False)
        sim.run(0.5, ChassisSpeeds(1.0, 0.0, 0.0))
        assert math.hypot(sim.true_pose.x_m, sim.true_pose.y_m) < 1e-6


class TestHeading:
    def test_gyro_dropout_keeps_heading_continuous(self, sim_drive):
        sim = sim_drive()
        spin = ChassisSpeeds(0, 0, 1.0)
        sim.run(1.0, spin)
        sim.physics.gyro_connected = False  # gyro unplugged mid-match
        # The NavX library takes a moment (about 0.3 s of real time) to
        # notice; the heading is frozen until then, like on the real robot.
        # Run loops at real-time pace so its clock gets there.
        deadline = time.monotonic() + 3.0
        while sim.drivetrain.gyro_inputs.connected and time.monotonic() < deadline:
            sim.run(0.02, spin)
            time.sleep(0.02)
        assert not sim.drivetrain.gyro_inputs.connected
        error_when_noticed = sim.drivetrain.heading_rad - sim.true_pose.heading_rad
        sim.run(1.0, spin)  # now the wheels keep the heading going
        error = sim.drivetrain.heading_rad - sim.true_pose.heading_rad
        assert abs(error - error_when_noticed) < math.radians(3)
        sim.physics.gyro_connected = True  # and back: no jump
        sim.run(0.5, spin)
        assert sim.drivetrain.gyro_inputs.connected
        after = sim.drivetrain.heading_rad - sim.true_pose.heading_rad
        assert abs(after - error) < math.radians(3)

    def test_gyro_drift_moves_the_heading(self, sim_drive):
        sim = sim_drive(gyro_drift_rad_per_s=0.01)
        sim.run(2.0)
        assert sim.drivetrain.heading_rad == pytest.approx(0.02, abs=0.005)
        assert sim.true_pose.heading_rad == 0.0

    def test_reset_pose(self, sim_drive):
        sim = sim_drive()
        sim.run(0.5, ChassisSpeeds(1.0, 0, 0.5))
        sim.drivetrain.reset_pose(Pose2d(3.0, 2.0, Rotation2d(math.pi)))
        sim.run(0.02)
        pose = sim.drivetrain.pose
        assert (pose.X(), pose.Y()) == pytest.approx((3.0, 2.0), abs=0.05)
        assert angle_error(pose.rotation().radians(), math.pi) < math.radians(2)


