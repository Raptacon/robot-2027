"""
Tests for the drivetrain on the simulated robot. The math has its own tests in test_swerve_math.py.

Generated by Claude. The drivetrain is built from real SPARK MAX, CANcoder
and NavX objects, with the simulator's physics behind them (the
``sim_drive`` fixture), so these check the same code that runs on the robot:

- driving straight (field-relative) while rotating doesn't drift off the line,
  and odometry matches where the simulated robot really is;
- wheels are seeded from the absolute encoders wherever they point at boot;
- the wrong gear preset makes odometry drift by the gear ratio;
- an unplugged gyro hands the heading to the wheels without a jump.

A dead or slow absolute encoder can't be made in the CANcoder simulator, so
those checks are in test_module.py, on the module alone.
"""

