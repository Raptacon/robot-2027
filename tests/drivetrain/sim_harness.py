"""
Test helper: the real drivetrain code driving the simulated robot.

Generated by Claude. :class:`SimDrive` builds the drivetrain the same way
``robot.py`` does (real ``SparkMax``, ``CANcoder`` and NavX objects from the
robot config) and puts :class:`~sim.swerve_physics.SwervePhysics` behind it,
the same physics ``robotpy sim`` uses. Tests then read the robot's true
position from the physics and compare it with what the robot code thinks.

Use the ``sim_drive`` fixture (``tests/drivetrain/conftest.py``), which
calls :meth:`SimDrive.close` after each test.

Reusing devices between tests:
    A ``SparkMax`` can't be created twice with one CAN ID, REV's simulator
    leaves part of a deleted SPARK MAX behind (so a new one with that ID
    reads nothing), and deleting a NavX while its thread runs can crash.
    So every test in one process shares the same SPARK MAX objects (one per
    CAN ID) and one NavX. Each new :class:`SimDrive` configures the SPARK
    MAXes from defaults again, as the robot does at every boot, and zeroes
    their simulators, like switching the robot off and on.

Needs Phoenix 6 and the NavX library; tests that import this file are
skipped where they aren't installed (RobotPy 2027 for now).
"""

import math
from collections.abc import Callable, Mapping

import commands2
import pytest
import rev
import wpilib
from wpilib.simulation import DriverStationSim, isTimingPaused, stepTiming

pytest.importorskip("phoenix6")

from config.robot_config import RobotConfig  # noqa: E402
from config.robots.swerve_test_bot import CONFIG  # noqa: E402
from sim.swerve_physics import CornerSim, SwervePhysics  # noqa: E402
from sim.swerve_physics import DCMotor  # noqa: E402
from subsystem.drivetrain.drivetrain_hardware import build_drivetrain  # noqa: E402
from subsystem.drivetrain.io import module_io_spark  # noqa: E402
from subsystem.drivetrain.io.gyro_io import GyroIO  # noqa: E402
from subsystem.drivetrain.io.gyro_io_onboard import has_onboard_imu  # noqa: E402
from subsystem.drivetrain.swerve_math import ChassisSpeeds  # noqa: E402

LOOP_S = 0.02

SENSOR_TIMEOUT_S = 2.0
"""Real time to wait for the NavX and CANcoder simulators (they normally answer in 20 ms)."""

_sparks: dict[int, rev.SparkMax] = {}
_make_new_spark_max = module_io_spark.make_spark_max


def _shared_spark_max(can_id: int) -> rev.SparkMax:
    """Hand out one SPARK MAX per CAN ID for the whole test run."""
    if can_id not in _sparks:
        _sparks[can_id] = _make_new_spark_max(can_id)
    return _sparks[can_id]


module_io_spark.make_spark_max = _shared_spark_max

_navx: GyroIO | None = None


def shared_gyro(config: RobotConfig = CONFIG) -> GyroIO | None:
    """The NavX every test shares, or ``None`` on SystemCore (``build_drivetrain`` makes its IMU)."""
    global _navx
    if has_onboard_imu():
        return None
    pytest.importorskip("navx")
    if _navx is None:
        from subsystem.drivetrain.io.gyro_io_navx import GyroIONavX

        _navx = GyroIONavX(config)
    return _navx


def _power_on(spark: rev.SparkMax) -> None:
    """Zero a reused SPARK MAX's simulator, as if the robot had just been switched on."""
    spark.stopMotor()
    spark_sim = rev.SparkMaxSim(spark, DCMotor.NEO(1))
    spark_sim.setAppliedOutput(0.0)
    spark_sim.setVelocity(0.0)
    spark_sim.setPosition(0.0)
    spark_sim.getRelativeEncoderSim().setPosition(0.0)


def angle_error(a: float, b: float) -> float:
    """Smallest difference between two angles, radians."""
    return abs(math.remainder(a - b, math.tau))


class SimDrive:
    """The real drivetrain on the simulated robot.

    Args:
        config: The robot config the drive code uses.
        corners: Optional :class:`~sim.swerve_physics.CornerSim` per corner name.
        enabled: Start with the robot enabled (the SPARK MAXes only drive
            while enabled, like on the real robot).
        **physics_options: More :class:`~sim.swerve_physics.SwervePhysics`
            options (``gyro_drift_rad_per_s``, ``battery``).

    Attributes:
        drivetrain: The drivetrain under test.
        physics: The physics behind it (``true_pose``, ``modules`` and so on).
        robot_loop: What runs each 20 ms loop after the physics. Defaults to
            ``drivetrain.periodic``; set it to a command scheduler's ``run``
            to run commands too.
    """

    def __init__(
        self,
        config: RobotConfig = CONFIG,
        corners: Mapping[str, CornerSim] | None = None,
        enabled: bool = True,
        **physics_options,
    ) -> None:
        self.drivetrain = build_drivetrain(config, loop_period_s=LOOP_S, gyro=shared_gyro(config))
        for module in self.drivetrain.modules:
            _power_on(module.io.drive)  # pyright: ignore[reportAttributeAccessIssue]
            _power_on(module.io.steer)  # pyright: ignore[reportAttributeAccessIssue]
        self.physics = SwervePhysics(
            self.drivetrain, corners, battery=physics_options.pop("battery", False), **physics_options
        )
        self.robot_loop: Callable[[], None] = self.drivetrain.periodic
        self.set_enabled(enabled)
        if isTimingPaused():
            stepTiming(LOOP_S)  # let the NavX library read the new heading
        assert self.physics.wait_for_sensors(encoders=True, timeout_s=SENSOR_TIMEOUT_S), (
            "simulated sensors never reported"
        )
        self.loop()  # seed the modules

    def set_enabled(self, enabled: bool) -> None:
        """Enable or disable the simulated robot."""
        DriverStationSim.setEnabled(enabled)
        DriverStationSim.notifyNewData()

    def loop(self, wait_for_encoders: bool | None = None) -> None:
        """Run one 20 ms loop: physics, then the robot code.

        Args:
            wait_for_encoders: Wait for the CANcoders to report this loop's
                angle. Defaults to doing so while disabled, when the robot
                code uses them.
        """
        self.physics.step(LOOP_S)
        if isTimingPaused():
            # After the physics: with paused timing the NavX library only
            # reads its simulator when simulated time moves on.
            stepTiming(LOOP_S)
        if wait_for_encoders is None:
            wait_for_encoders = wpilib.RobotState.isDisabled()
        # A slow CI machine can take a while; failing here beats running the
        # robot code on last loop's readings and failing somewhere confusing.
        assert self.physics.wait_for_sensors(encoders=wait_for_encoders, timeout_s=SENSOR_TIMEOUT_S), (
            "simulated gyro or CANcoders didn't report this loop's values in time"
        )
        self.robot_loop()

    def run(self, seconds: float, speeds: ChassisSpeeds | None = None, field_relative: bool = True) -> None:
        """Run loops for ``seconds``, driving with ``speeds`` if given."""
        for _ in range(round(seconds / LOOP_S)):
            self.loop()
            if speeds is not None:
                self.drivetrain.drive(speeds, field_relative=field_relative)

    def close(self) -> None:
        """Stop the motors and let go of the drivetrain, ready for the next :class:`SimDrive`."""
        if "drivetrain" not in self.__dict__:
            return  # already closed
        commands2.CommandScheduler.getInstance().cancelAll()
        commands2.CommandScheduler.resetInstance()  # it holds the drivetrain subsystem
        for module in self.drivetrain.modules:
            module.stop()
        self.__dict__.clear()

    @property
    def true_pose(self):
        """Where the robot really is (:class:`~subsystem.drivetrain.swerve_math.Pose`)."""
        return self.physics.true_pose

    def true_angles(self) -> list[float]:
        """Where each wheel really points, radians (FL, FR, BL, BR)."""
        return [m.true_angle_rad for m in self.physics.modules]
